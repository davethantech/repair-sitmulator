"use strict";
const assert=require("node:assert/strict");
const P=require("../pcb-core.js"),J=require("../academy/pcb-journey-core.js");
const E=require("../cad/erc-core.js"),F=require("../factory-core.js");
assert.equal(J.DAYS.length,5);
assert.equal(J.STEPS.length,12);
assert.equal(new Set(J.STEPS.map(x=>x.id)).size,12);
assert.match(J.EXTERNAL,/^https:\/\/app\.pantech\.ai\/pcbdesign/);
const led=J.brief({kind:"led"}),calc=J.ledCalculation(led);
assert.ok(Math.abs(calc.targetOhms-1000)<1e-10);
assert.ok(Math.abs(calc.actualMa-3)<1e-10);
assert.ok(Math.abs(calc.resistorPowerW-.009)<1e-10);
assert.equal(J.nearestE12(990),1000);
assert.equal(J.nearestE12(2200),2200);
assert.equal(J.nearestE12(150),150);
assert.throws(()=>J.brief({kind:"led",supplyV:1,forwardV:2}),/Source must exceed/);
assert.throws(()=>J.brief({kind:"led",targetMa:500}),/Target LED current/);
assert.throws(()=>J.brief({kind:"led",supplyV:230}),/Isolated supply voltage/);
assert.throws(()=>J.brief({kind:"led",title:"x"}),/title/);
assert.throws(()=>J.brief({kind:"invalid"}),/Unknown supported/);
assert.equal(J.recommend("Design an isolated USB-C 5V sink with a LED").kind,"usb");
assert.equal(J.recommend("Build a 3.3V sensor module with microcontroller").kind,"regulator");
assert.equal(J.recommend("Create a basic 5V LED indicator and fuse").kind,"led");
assert.ok(J.recommend("Please use a lithium battery charging circuit").warnings.some(s=>s.includes("lithium")));
assert.throws(()=>J.recommend("short"),/at least eight/);
const board=J.template(led),review=J.review(board,led);
assert.equal(review.spec.kind,"led");
assert.equal(board.schema,"boardlab.pcb.v1");
assert.equal(review.board.connections,100);
assert.equal(review.checks.drcErrors,0);
assert.equal(review.checks.ercErrors,0);
assert.equal(review.trainingProgress,"9/12");
assert.equal(review.stages.filter(s=>s.status==="completed").length,9);
assert.equal(review.stages.filter(s=>s.status==="external").length,3);
assert.equal(review.canFabricate,false);
assert.equal(review.manufacturerApproved,false);
assert.ok(review.guidance.some(g=>g.message.includes("supplier")));
for(const name of ["regulator","usb"]){
 const r=J.review(J.template({kind:name}),{kind:name});
 assert.equal(r.board.connections,0,name);
 assert.ok(r.checks.ercErrors>0,name);
 assert.ok(r.stages.find(x=>x.id==="footprints").status==="action-required");
 assert.equal(r.canFabricate,false);
}
const unrouted=P.validateImport(board);
unrouted.tracks=unrouted.tracks.filter(x=>x.net!=="LED_A");
const bad=J.review(unrouted,led);
assert.equal(bad.stages.find(x=>x.id==="routing").status,"action-required");
assert.ok(bad.board.connections<100);
assert.equal(bad.stages.find(x=>x.id==="manufacturing").status,"external");
const packageData=J.handoff(board,led);
assert.equal(packageData.metadata.manufacturerApproved,false);
assert.equal(packageData.metadata.release,"EDUCATION_ONLY");
assert.ok(packageData.files.bomCsv.includes("NOT ASSIGNED"));
assert.ok(packageData.files.kicadPcb.includes("(kicad_pcb"));
assert.ok(packageData.files.pickPlaceCsv.includes("UNVERIFIED"));
assert.ok(packageData.files.schematicJson.includes("boardlab.schematic.v1"));
assert.deepEqual(P.validateImport(JSON.parse(packageData.files.pcbJson)),board);
assert.ok(packageData.checklist.length>=5);
assert.equal(packageData.externalCourse,J.EXTERNAL);
assert.ok(E.check(E.schematicFromPCB(board),board).errors===0);
assert.ok(F.report(board).blockers===0);
console.log("PASS: Pantech-referenced independent PCB journey; five days, 12 evidence gates, values, DRC/ERC, safe handoff");
