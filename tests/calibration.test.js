"use strict";
const assert=require("node:assert/strict"),M=require("../simulation/mna-core.js"),C=require("../validation/golden-core.js");
const reference=C.syntheticFixture(M.EXAMPLES.rc,"transient");
const report=C.compare(reference);
assert.equal(report.observations,6);
assert.equal(report.failed,0);
assert.equal(report.passed,true);
assert.equal(report.maxAbsErrorV,0);
assert.equal(report.kind,"synthetic");
assert.equal(report.manufacturerApproved,false);
assert.equal(report.calibratedAgainstRealHardware,false);
const modified=JSON.parse(JSON.stringify(reference));modified.probes[0].samples[1].volts+=1.2;
const mismatch=C.compare(modified);
assert.equal(mismatch.passed,false);
assert.equal(mismatch.failed,1);
assert.ok(mismatch.rmseV>.4);
const dc=C.syntheticFixture(M.EXAMPLES.divider,"op");
assert.equal(C.compare(dc).passed,true);
const missing=JSON.parse(JSON.stringify(reference));missing.provenance={kind:"physical",source:"Lab bench without metadata"};
assert.throws(()=>C.compare(missing),/Physical measurements need instrument/);
const physical=JSON.parse(JSON.stringify(reference));
physical.provenance={kind:"physical",source:"USER-DECLARED physical bench reference",instrument:"User external digital multimeter",operator:"Declared technician",date:"2026-11-21",boardRevision:"LAB-R1"};
const summary=C.compare(physical);assert.equal(summary.referenceType.startsWith("USER-DECLARED"),true);
assert.equal(summary.calibratedAgainstRealHardware,false,"Unattested physical claims cannot auto-calibrate");
const wrong=JSON.parse(JSON.stringify(reference));wrong.probes[0].node="SHADOW_NET";
assert.throws(()=>C.validate(wrong),/unknown circuit net/);
assert.throws(()=>C.validate({...reference,probes:[]}),/probe datasets/);
assert.throws(()=>C.validate({...reference,provenance:{kind:"synthetic",source:""}}),/source required/);
console.log("PASS v6: synthetic golden traces, out-of-tolerance failure, explicit physical provenance and unapproved release state");
