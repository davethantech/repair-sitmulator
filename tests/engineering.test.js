"use strict";
const assert=require("node:assert/strict");
const P=require("../pcb-core.js"),F=require("../factory-core.js"),M=require("../embedded-core.js"),S=require("../signal-core.js"),R=require("../rework-core.js");
const eq=(x,y,tol=1e-6)=>assert.ok(Math.abs(x-y)<=tol,"Expected "+x+" ≈ "+y);
const ref=P.routedExample(),dfm=F.report(ref),usb=F.report(P.getTemplate("usb"));
assert.equal(dfm.blockers,0,"Routed training reference should have no modeled blocker");
assert.ok(usb.blockers>=1,"Conceptual USB-C footprint must be blocked for fabrication");
assert.equal(dfm.canRelease,false);assert.ok(F.bom(ref).includes("NOT ASSIGNED"));
assert.ok(F.pickPlace(ref).includes("UNVERIFIED CENTROID"));
assert.ok(F.drills(ref).includes("Mechanical mounting"));
const panel=F.panelize(ref,{cols:2,rows:3,gap:3,rail:8});
eq(panel.widthMm,187);eq(panel.heightMm,184);assert.equal(panel.copies,6);
assert.throws(()=>F.panelize(ref,{cols:2.5}));
const invalid=P.routedExample();invalid.vias[0].drill=.1;
assert.ok(F.report(invalid,{minDrill:.2}).issues.some(i=>i.code==="drill_below_profile"));
for(const [name,program] of Object.entries(M.TEMPLATES)){const instance=M.make(program);const result=M.run(instance);assert.equal(result.done,true,name);assert.ok(instance.halted);}
const blink=M.make(M.TEMPLATES.blink);M.run(blink);assert.equal(blink.timeMs,1600);assert.equal(blink.regs[0],4);
assert.equal(blink.uart.at(-1).text,"Blink completed");
assert.throws(()=>M.compile("JMP LOOP"),/Undefined jump label/);
assert.throws(()=>M.compile("BAD R1 1"),/Bad instruction/);
assert.throws(()=>M.compile("OUT P0 999"),/OUT expects/);
assert.throws(()=>M.compile("LOOP:\nLOOP:\nHALT"),/duplicate label/);
const nack=M.make(M.TEMPLATES.sensor,{fault:"i2c_nack"});M.run(nack);assert.equal(nack.ioErrors,1);
const brown=M.make(M.TEMPLATES.blink,{fault:"brownout"});M.run(brown);assert.match(brown.reason,/Brownout reset/);
const led=M.make(M.TEMPLATES.blink,{fault:"led_open"});M.step(led);M.step(led);assert.equal(M.pins(led).ledOn,false);
const adc=M.make(M.TEMPLATES.adc,{adcV:1.65});M.run(adc);assert.equal(adc.regs[1],512);
const matched=S.waveform({impedanceOhm:50,sourceOhm:50,loadOhm:50,stepV:3.3});
eq(matched.maxV,1.65,.0001);eq(matched.overshootV,0);
const open=S.waveform({impedanceOhm:50,sourceOhm:50,loadOhm:"open"});
eq(open.maxV,3.3,.0001);eq(open.parameters.loadReflection,1);
const mismatched=S.waveform({impedanceOhm:50,sourceOhm:0,loadOhm:100});
assert.ok(mismatched.overshootV>1);
const d=S.timing({lengthMm:100,erEffective:2.9,bitRateMbps:100});
assert.ok(d.propagationNs>.1&&d.propagationNs<1&&d.delayUI>0);
assert.throws(()=>S.calculate({impedanceOhm:0}),/outside/);
let rw=R.make();assert.equal(R.supply(rw,true).ok,true);
assert.equal(R.heat(rw,{},1).ok,false,"Powered hot-air use forbidden");
R.supply(rw,false);
for(let i=0;i<15;i++)R.heat(rw,{airC:310,airflow:.7,distanceMm:4},1);
assert.equal(R.remove(rw).ok,true);
assert.equal(R.place(rw).ok,true);
for(let i=0;i<10;i++)R.heat(rw,{airC:310,airflow:.7,distanceMm:4},1);
R.cool(rw,60);assert.equal(R.inspect(rw).passed,true);
const damaged=R.make();for(let i=0;i<25;i++)R.heat(damaged,{airC:400,airflow:1,distanceMm:2},1);
assert.equal(R.inspect(damaged).passed,false);
let dirty=R.make({corrosion:true,bridge:true});assert.equal(R.inspect(dirty).passed,false);
R.clean(dirty);R.bridge(dirty);assert.equal(dirty.corrosion,false);assert.equal(dirty.bridge,false);
console.log("PASS v5: PCB DFM/assembly, MCU firmware & faults, SI reflections, thermal rework & safety");
